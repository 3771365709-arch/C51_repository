/*
 * ===========================================================================
 *  51单片机定时器中断版流水灯（SDCC + 普中 STC89C52）
 * ===========================================================================
 *  改进点：用 T0 定时器中断做时基，替代阻塞式 delay_ms
 *          主循环可同时做其他事（这里演示：主循环啥也不干，等中断）
 *  硬件：8 LED 接 P2 口，共阳；晶振 11.0592MHz
 *  机制：T0 每 50ms 溢出一次 → 中断里计数到 6 次=300ms → 移位一次
 * ===========================================================================
 */
#include <mcs51/8052.h>

#define LED_PORT P2

/* 全局变量（中断和主函数共享，必须用 volatile）*/
volatile unsigned int tick_50ms = 0;   // 50ms 计数
volatile unsigned char move_flag = 0;  // 移位标志：1=该移位了

/* 50ms @ 11.0592MHz 定时器初值（模式1，16位）
   50000us / (12/11.0592) ≈ 46083 计数
   65536 - 46083 = 19453 = 0x4BFD → TH0=0x4B, TL0=0xFD
   (实际可微调，这里取经验值) */
#define TH0_VAL 0x4B
#define TL0_VAL 0xFD

/* --------------------------------------------------------------------------
 *  T0 中断服务程序：中断号 1（SDCC 语法 __interrupt(1)）
 *  每 50ms 触发一次，累积到 6 次后置位移位标志
 * -------------------------------------------------------------------------- */
void timer0_isr(void) __interrupt(1)
{
    TH0 = TH0_VAL;        // 重装初值（模式1需手动重装）
    TL0 = TL0_VAL;
    tick_50ms++;
    if (tick_50ms >= 6)   // 6×50ms = 300ms
    {
        tick_50ms = 0;
        move_flag = 1;    // 通知主循环：可以移位了
    }
}

void main(void)
{
    unsigned char led = 0xFE;

    /* T0 初始化：模式1（16位定时器）*/
    TMOD = (TMOD & 0xF0) | 0x01;   // T0=M1=0,M0=1 → 模式1
    TH0 = TH0_VAL;
    TL0 = TL0_VAL;
    ET0 = 1;             // 允许 T0 中断
    EA  = 1;             // 开总中断
    TR0 = 1;             // 启动 T0

    LED_PORT = led;

    while (1)
    {
        if (move_flag)             // 主循环查标志，不阻塞
        {
            move_flag = 0;
            led = (unsigned char)((led << 1) | (led >> 7));  // 循环左移
            LED_PORT = led;
        }
        /* 这里可加入其他任务：按键扫描、串口处理等
           因为延时在中断里，主循环不被阻塞 */
    }
}
