/*
 * ===========================================================================
 *  51单片机流水灯控制程序（普中 STC89C52 开发板适配版）
 * ===========================================================================
 *  开发板硬件对应（以普中 A2/A3/A4 为参考，请按自己板子原理图核对）
 *  ----------------------------------------------------------
 *   - 主控芯片：STC89C52RC（DIP40）
 *   - 晶振    ：11.0592 MHz（普中标配，便于串口波特率精确）
 *   - LED     ：8个 LED 接 P2 口（P2.0~P2.7），共阳接法
 *              阳极接 VCC，阴极接 P2 引脚，低电平点亮
 *   - 独立按键：K1~K4 接 P3.0~P3.3，按下为低电平
 *   - 蜂鸣器  ：接 P1.5（默认不使用）
 *  ----------------------------------------------------------
 *  开发环境：Keil uVision5 + STC-ISP
 *  烧录方式：USB 串口下载（CH340），波特率 9600~115200 自适应
 * ===========================================================================
 */
#include <reg52.h>      // 包含 89C52 特殊功能寄存器定义（P0~P3、TMOD、TH0 等）
#include <intrins.h>    // 包含位操作库函数 _cror_ / _crol_（编译后对应 RL/RR 指令）

#define LED_PORT  P2    // 宏：把"LED_PORT"替换为"P2"，换板子改这里即可
#define KEY_SPEED P3^0  // K1 按键，用于切换流水速度（按一次变快/慢）

/* --------------------------------------------------------------------------
 *  函数：delay_ms
 *  作用：粗略毫秒级软件延时
 *  参数：ms = 需要延时的毫秒数
 *  说明：11.0592MHz 晶振下，内层 j 循环约消耗 1ms
 *       精确延时请用定时器中断，这里仅用于流水灯节奏控制
 * -------------------------------------------------------------------------- */
void delay_ms(unsigned int ms)
{
    unsigned int i, j;
    for (i = 0; i < ms; i++)
        for (j = 0; j < 110; j++);   // 11.0592MHz 下经验值约 1ms
}

/* --------------------------------------------------------------------------
 *  函数：main
 *  说明：P2 口的 8 位分别对应 8 个 LED
 *       初值 0xFE = 1111 1110，最低位为 0 → P2.0 输出低电平 → D1 亮
 *       _crol_ 循环左移 1 位，亮的 LED 从 P2.0 移到 P2.7，循环往复
 * -------------------------------------------------------------------------- */
void main(void)
{
    unsigned char led = 0xFE;     // 初值：1111 1110，P2.0 亮
    unsigned char speed = 300;   // 流水间隔，单位 ms，默认 300ms

    while (1)                    // 单片机主循环，必须死循环
    {
        LED_PORT = led;          // 把 led 值写入 P2 锁存器，LED 状态更新
        delay_ms(speed);         // 按当前速度延时

        led = _crol_(led, 1);    // 循环左移 1 位：0xFE→0xFD→0xFB→...→0x7F→0xFE

        /* 简易调速：按 K1 切换快慢档 */
        if (KEY_SPEED == 0)      // K1 按下（低电平有效）
        {
            delay_ms(20);       // 按键消抖，约 20ms
            if (KEY_SPEED == 0) /* 二次确认 */
            {
                /* 三档循环：300 → 150 → 600 → 300 */
                if (speed == 300)      speed = 150;   // 中速
                else if (speed == 150) speed = 600;  // 慢速
                else                  speed = 300;   // 恢复正常
                while (KEY_SPEED == 0); /* 松手检测，避免一直按住 */
            }
        }
    }
}
