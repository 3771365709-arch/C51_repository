/*
 * ===========================================================================
 *  51单片机串口调试示例（SDCC + 普中 STC89C52）
 * ===========================================================================
 *  功能：上位机发什么，单片机原样回发（echo），同时 LED 闪烁表示收到
 *  串口参数：9600 8N1（11.0592MHz 晶振下精确波特率）
 *  硬件：P3.0=RXD, P3.1=TXD，板载 CH340 转 USB 接电脑
 * ===========================================================================
 */
#include <mcs51/8052.h>

#define LED_PORT P2

/* 简单延时（仅用于 LED 闪烁指示）*/
void delay_ms(unsigned int ms)
{
    unsigned int i, j;
    for (i = 0; i < ms; i++)
        for (j = 0; j < 110; j++);
}

/* --------------------------------------------------------------------------
 *  串口初始化：9600 8N1
 *  T1 做波特率发生器，模式2（8位自动重装）
 *  11.0592MHz / 12 / 32 / (256-TH1) = 9600 → TH1 = 253 = 0xFD
 * -------------------------------------------------------------------------- */
void uart_init(void)
{
    TMOD = (TMOD & 0x0F) | 0x20;   // T1 模式2（8位自动重装）
    TH1 = 0xFD;                    // 9600 波特率
    TL1 = 0xFD;
    SCON = 0x50;                   // 模式1（8位UART），允许接收 (SM0=0,SM1=1,REN=1)
    TR1 = 1;                       // 启动 T1
    ES  = 1;                       // 允许串口中断
    EA  = 1;                       // 开总中断
}

/* 发送一个字节（查询方式）*/
void uart_send(unsigned char c)
{
    SBUF = c;
    while (TI == 0);   // 等待发送完成
    TI = 0;            // 清发送标志
}

/* 发送字符串 */
void uart_send_str(const char *s)
{
    while (*s)
        uart_send(*s++);
}

/* --------------------------------------------------------------------------
 *  串口中断：中断号 4
 *  收到数据 → 回发 → LED 翻转
 * -------------------------------------------------------------------------- */
void uart_isr(void) __interrupt(4)
{
    unsigned char c;
    if (RI)                // 接收中断
    {
        RI = 0;            // 清接收标志
        c = SBUF;          // 读数据
        SBUF = c;          // 回发（echo）
        while (TI == 0);   // 等回发完成
        TI = 0;
        LED_PORT = ~LED_PORT;  // LED 翻转表示收到
    }
    else if (TI)           // 发送中断（用查询发送时也会触发，这里清掉）
    {
        TI = 0;
    }
}

void main(void)
{
    uart_init();
    LED_PORT = 0xFE;
    uart_send_str("Hello from STC89C52! Send any byte to echo.\r\n");

    while (1)
    {
        /* 主循环空闲，串口收发全在中断里 */
        /* 这里也可以做流水灯、按键扫描等 */
        delay_ms(500);
        LED_PORT = (unsigned char)((LED_PORT << 1) | (LED_PORT >> 7));
    }
}
